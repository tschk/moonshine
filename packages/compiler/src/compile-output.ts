import { createHash } from "node:crypto";
import {
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { basename, dirname, join, relative, sep } from "node:path";
import type { CrepusGraph } from "./compile-graph";

async function directory(path: string): Promise<void> {
  try {
    await mkdir(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
  }
  const info = await lstat(path);
  if (!info.isDirectory() || info.isSymbolicLink())
    throw new Error(`Unsafe compiled module directory: ${path}`);
}

/** Publish immutable compiler bytes before atomically switching the public entry. */
export async function publishCrepusGraph(
  output: string,
  graph: CrepusGraph,
): Promise<void> {
  const hash = createHash("sha256");
  hash.update(JSON.stringify([graph.entry, graph.files]));
  const digest = hash.digest("hex");
  const parent = dirname(output);
  const generated = join(parent, ".moonshine-compiled");
  const source = join(generated, basename(output));
  await directory(generated);
  await directory(source);
  const destination = join(source, digest);
  const staged = await mkdtemp(join(source, ".pending-"));
  try {
    for (const file of graph.files) {
      const path = join(staged, file.path);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, file.source);
    }
    try {
      await rename(staged, destination);
    } catch (error) {
      if (
        !["EEXIST", "ENOTEMPTY"].includes(
          (error as NodeJS.ErrnoException).code ?? "",
        )
      )
        throw error;
    }
    // A pre-existing digest is reusable only when every referenced byte matches.
    const rootInfo = await lstat(destination);
    if (!rootInfo.isDirectory() || rootInfo.isSymbolicLink())
      throw new Error(`Unsafe compiled module directory: ${destination}`);
    for (const file of graph.files) {
      const parts = file.path.split("/");
      let path = destination;
      for (const part of parts) {
        path = join(path, part);
        if ((await lstat(path)).isSymbolicLink())
          throw new Error(`Unsafe compiled module path: ${path}`);
      }
      if ((await readFile(path, "utf8")) !== file.source)
        throw new Error(`Compiled module contents differ: ${path}`);
    }
    const entry = graph.files.find((file) => file.path === graph.entry)!;
    const hasDefault = new Bun.Transpiler({ loader: "ts" })
      .scan(entry.source)
      .exports.includes("default");
    const specifier = JSON.stringify(
      "./" +
        relative(parent, join(destination, graph.entry)).split(sep).join("/"),
    );
    const facade = `// Generated by moonshine compile; compiler modules are preserved unchanged.\nexport * from ${specifier};\n${hasDefault ? `export { default } from ${specifier};\n` : ""}`;
    const pending = await mkdtemp(join(parent, ".moonshine-entry-"));
    try {
      const path = join(pending, "entry.ts");
      await writeFile(path, facade);
      await rename(path, output);
    } finally {
      await rm(pending, { recursive: true, force: true });
    }
  } finally {
    await rm(staged, { recursive: true, force: true });
  }
}
